# Build simhub\ScApiPlugin.cs into build\ScApi.SimHub.dll
#
# Compiled with Roslyn csc directly rather than MSBuild/NuGet: the plugin is a
# single source file whose references all resolve to DLLs that already exist,
# so a project system adds nothing but failure modes.
#
# Targets .NET Framework 4.7.2 -- see scripts\common.ps1 for why.
#
# References resolve in this order:
#   1. -RefDir <dir>      an explicit reference directory (this is what CI uses,
#                         holding the facades from simhub\refs\ -- see
#                         simhub\refs\README.md)
#   2. the local SimHub installation (the real assemblies; preferred for a
#      developer build, since it compiles against exactly what will load)
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File scripts\build_simhub_plugin.ps1
#   powershell -ExecutionPolicy Bypass -File scripts\build_simhub_plugin.ps1 -Install
#   powershell -ExecutionPolicy Bypass -File scripts\build_simhub_plugin.ps1 -RefDir build\refs

param(
    [switch]$Install,
    [string]$RefDir,
    [string]$FrameworkDir,
    [string]$Csc,
    [string]$OutDir = 'build',
    [string]$Version
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
. (Join-Path $PSScriptRoot 'common.ps1')

$simhub = @(
    'C:\Program Files (x86)\SimHub',
    'C:\Program Files\SimHub'
) | Where-Object { Test-Path $_ } | Select-Object -First 1

if ($RefDir) {
    $refs = if ([System.IO.Path]::IsPathRooted($RefDir)) { $RefDir } else { Join-Path $root $RefDir }
    if (-not (Test-Path $refs)) { throw "-RefDir does not exist: $refs" }
    $refSource = "reference directory $refs"
} elseif ($simhub) {
    $refs = $simhub
    $refSource = "SimHub installation $simhub"
} else {
    throw @'
SimHub not found, and no -RefDir given. Either install SimHub, or build the
reference facades first:
  scripts\build_simhub_refs.ps1 -OutDir build\refs -Log4Net <...> -Newtonsoft <...>
  scripts\build_simhub_plugin.ps1 -RefDir build\refs
'@
}

$csc = Resolve-Csc $Csc
$fw = Resolve-FrameworkDir $FrameworkDir

if (-not $Version) {
    # Single source of truth for the version: scapi\__init__.py.
    $initPath = Join-Path $root 'scapi\__init__.py'
    $m = [regex]::Match((Get-Content $initPath -Raw), '__version__\s*=\s*"([^"]+)"')
    $Version = if ($m.Success) { $m.Groups[1].Value } else { '0.0.0' }
}

Write-Output "references: $refSource"
Write-Output "compiler  : $csc"
Write-Output "framework : $fw"
Write-Output "version   : $Version"

$outDirFull = if ([System.IO.Path]::IsPathRooted($OutDir)) { $OutDir } else { Join-Path $root $OutDir }
New-Item -ItemType Directory -Force $outDirFull | Out-Null
$out = Join-Path $outDirFull 'ScApi.SimHub.dll'

# Framework references. The WPF assemblies are needed when compiling against
# the real SimHub.Plugins.dll, because it exposes WPF types in its public
# surface even though this plugin has no UI. The facades do not, so they are
# filtered out when absent rather than being a hard requirement.
$fwRefs = @(
    'mscorlib.dll', 'System.dll', 'System.Core.dll', 'System.Net.Http.dll',
    'System.Xml.dll', 'WindowsBase.dll', 'PresentationCore.dll',
    'PresentationFramework.dll'
) | ForEach-Object { Join-Path $fw $_ } | Where-Object { Test-Path $_ }

$shRefs = @(
    'SimHub.Plugins.dll', 'SimHub.Logging.dll', 'GameReaderCommon.dll',
    'Newtonsoft.Json.dll',
    # SimHub.Logging exposes log4net's ILog in its public surface, so the
    # compiler needs it even though this plugin never names log4net directly.
    'log4net.dll'
) | ForEach-Object { Join-Path $refs $_ }
foreach ($r in $shRefs) { if (-not (Test-Path $r)) { throw "missing reference: $r" } }

# Version stamping, generated rather than committed so it cannot drift.
$asmInfo = Join-Path $outDirFull 'AssemblyInfo.generated.cs'
$fileVersion = if ($Version -match '^\d+(\.\d+){0,3}$') { $Version } else { '0.0.0' }
@"
// Generated by scripts\build_simhub_plugin.ps1 -- do not edit, do not commit.
using System.Reflection;

[assembly: AssemblyTitle("sc-api Star Citizen Telemetry")]
[assembly: AssemblyProduct("sc-api")]
[assembly: AssemblyDescription("Star Citizen haptic telemetry for SimHub, via the D-BOX LiveMotion protocol")]
[assembly: AssemblyVersion("$fileVersion")]
[assembly: AssemblyFileVersion("$fileVersion")]
[assembly: AssemblyInformationalVersion("$Version")]
"@ | Set-Content -Path $asmInfo -Encoding UTF8

$refArgs = ($fwRefs + $shRefs) | ForEach-Object { "/reference:`"$_`"" }

$cscArgs = @(
    '/nologo', '/target:library', '/optimize+', '/warn:3', '/nostdlib+',
    '/langversion:7.3',
    "/out:$out"
) + $refArgs + @(
    (Join-Path $root 'simhub\ScApiPlugin.cs'),
    $asmInfo
)

& $csc $cscArgs
if ($LASTEXITCODE -ne 0) { throw "csc failed with exit code $LASTEXITCODE" }

$dll = Get-Item $out
Write-Output ''
Write-Output ("built {0} ({1:N0} bytes)" -f $dll.FullName, $dll.Length)

if ($Install) {
    if (-not $simhub) { throw 'SimHub is not installed here; nothing to install into.' }
    # SimHub loads plugins from its own directory.
    $dest = Join-Path $simhub $dll.Name
    try {
        Copy-Item $dll.FullName $dest -Force
        Write-Output "installed -> $dest"
        Write-Output 'Restart SimHub, then enable the plugin when prompted.'
    } catch {
        Write-Output "could not copy to $dest : $($_.Exception.Message)"
        Write-Output 'SimHub lives under Program Files, so this needs an elevated shell.'
    }
}
